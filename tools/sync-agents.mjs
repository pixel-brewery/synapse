// #region Imports

import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, lstat, rm, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// #endregion

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');

async function filesUnder(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    const files = [];

    for (const entry of entries) {
        const path = join(directory, entry.name);

        if (entry.isSymbolicLink())
            throw new Error(`AI configuration cannot contain a symlink: ${path}`);

        if (entry.isDirectory()) files.push(...(await filesUnder(path)));
        else if (entry.isFile()) files.push(path);
    }

    return files.sort();
}

async function readOptional(path) {
    try {
        const metadata = await lstat(path);

        if (metadata.isSymbolicLink())
            throw new Error(`Refusing AI configuration symlink: ${path}`);

        return await readFile(path, 'utf8');
    } catch (error) {
        if (error.code === 'ENOENT') return undefined;

        throw error;
    }
}

async function assertSafeParents(root, target) {
    for (let parent = dirname(target); parent !== root; parent = dirname(parent)) {
        const pathFromRoot = relative(root, parent);

        if (
            pathFromRoot === '..' ||
            pathFromRoot.startsWith(`..${sep}`) ||
            isAbsolute(pathFromRoot)
        )
            throw new Error('Invalid generated path.');

        try {
            if ((await lstat(parent)).isSymbolicLink())
                throw new Error(`Refusing symlink parent: ${parent}`);
        } catch (error) {
            if (error.code !== 'ENOENT') throw error;
        }
    }
}

function validateReferences(path, content, available, root) {
    const missing = [];
    const prose = content.replace(/```[\s\S]*?```/gu, '');

    for (const match of prose.matchAll(/\[[^\]]*\]\(([^)]+)\)/gu)) {
        const reference = match[1];

        if (/^(?:https?:|mailto:|#)/u.test(reference)) continue;

        const target = resolve(dirname(path), reference.split('#')[0]);

        if (!available.has(target)) missing.push(`${relative(root, path)} -> ${reference}`);
    }

    return missing;
}

/**
 * Synchronize or validate deterministic client projections without invoking AI CLIs.
 */
export async function syncAgents({ root = repository, write = false } = {}) {
    root = resolve(root);

    const configuration = JSON.parse(await readFile(join(root, '.agents/config.json'), 'utf8'));

    if (configuration.skill !== 'synapse-architect')
        throw new Error('The sole architecture skill must be synapse-architect.');

    const skillDirectory = join(root, '.agents/skills', configuration.skill);
    const canonical = await filesUnder(skillDirectory);
    const registry = JSON.parse(await readFile(join(root, configuration.mcpRegistry), 'utf8'));
    const servers = registry.servers;
    const codex = [
        '# Generated by yarn agents:sync. Edit .vscode/mcp.json instead.\n',
        '[features]',
        'multi_agent = true',
        '',
    ];
    const claude = {};
    const opencode = {};

    for (const [name, server] of Object.entries(servers)) {
        if (!/^[a-z][a-z0-9-]*$/u.test(name)) throw new Error(`Invalid MCP name: ${name}`);

        if (
            server.type !== 'stdio' ||
            typeof server.command !== 'string' ||
            !Array.isArray(server.args)
        ) {
            throw new Error(
                `Unsupported MCP configuration for ${name}; define an explicit projection first.`,
            );
        }

        if (
            server.env ||
            Object.keys(server).some((key) => /token|secret|password|credential/iu.test(key))
        ) {
            throw new Error('Literal credential configuration is not supported.');
        }

        codex.push(
            `[mcp_servers.${name}]`,
            `command = ${JSON.stringify(server.command)}`,
            `args = ${JSON.stringify(server.args)}`,
            '',
        );
        claude[name] = { type: 'stdio', command: server.command, args: server.args };
        opencode[name] = {
            type: 'local',
            command: [server.command, ...server.args],
            enabled: true,
        };
    }

    const skillPath = `.agents/skills/${configuration.skill}/SKILL.md`;
    const header =
        '<!-- Generated by yarn agents:sync. Edit AGENTS.md or the canonical skill. -->\n';
    const mandate = `Read and apply \`AGENTS.md\` and \`${skillPath}\` before every task, including delegated work. Use only Synapse Architect for architecture, source, testing and API-documentation rules. Follow its reference router.\n`;
    const output = new Map([
        ['CODEX.md', `${header}\n# Codex adapter\n\n${mandate}`],
        [
            'CLAUDE.md',
            `${header}\n# Claude Code adapter\n\n@AGENTS.md\n@${skillPath}\n\n${mandate}`,
        ],
        ['.github/copilot-instructions.md', `${header}\n# Copilot adapter\n\n${mandate}`],
        ['.codex/config.toml', `${codex.join('\n').trimEnd()}\n`],
        ['.mcp.json', `${JSON.stringify({ mcpServers: claude }, null, 2)}\n`],
        [
            'opencode.json',
            `${JSON.stringify({ $schema: 'https://opencode.ai/config.json', instructions: ['AGENTS.md', skillPath], mcp: opencode }, null, 2)}\n`,
        ],
    ]);
    const available = new Set([join(root, 'AGENTS.md'), ...canonical]);
    const referenceFailures = [];

    for (const source of canonical) {
        const content = await readFile(source, 'utf8');

        if (source.endsWith('.md'))
            referenceFailures.push(...validateReferences(source, content, available, root));

        for (const mirror of configuration.skillMirrors) {
            output.set(
                join(mirror, configuration.skill, relative(skillDirectory, source)),
                content,
            );
        }
    }

    if (referenceFailures.length)
        throw new Error(`Broken canonical references:\n${referenceFailures.join('\n')}`);

    const differences = [];

    for (const [name, content] of output) {
        const target = join(root, name);

        await assertSafeParents(root, target);

        const actual = await readOptional(target);

        if (actual !== content) {
            differences.push(name);

            if (write) {
                await mkdir(dirname(target), { recursive: true });
                await writeFile(target, content);
            }
        }
    }

    for (const mirror of configuration.skillMirrors) {
        const directory = join(root, mirror, configuration.skill);
        let existing = [];

        try {
            existing = await filesUnder(directory);
        } catch (error) {
            if (error.code !== 'ENOENT') throw error;
        }

        for (const file of existing) {
            const name = relative(root, file);

            if (output.has(name)) continue;

            differences.push(name);

            if (write) await rm(file);
        }
    }

    return {
        differences,
        projections: output.size,
        skillDigest: createHash('sha256')
            .update(await readFile(join(skillDirectory, 'SKILL.md')))
            .digest('hex'),
    };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    try {
        const args = process.argv.slice(2);

        if (args.length !== 1 || !['--write', '--check'].includes(args[0]))
            throw new Error('Usage: sync-agents.mjs --write | --check');

        const result = await syncAgents({ write: args[0] === '--write' });

        if (args[0] === '--check' && result.differences.length) {
            throw new Error(
                `Generated AI configuration drift:\n${result.differences.join('\n')}\nRun yarn agents:sync.`,
            );
        }

        process.stdout.write(
            `AI projections ${args[0] === '--write' ? 'synchronized' : 'match'} (${result.projections} files).\n`,
        );
    } catch (error) {
        process.stderr.write(`${error.message}\n`);
        process.exitCode = 1;
    }
}
